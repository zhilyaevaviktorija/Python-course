# 3. футболка - зеленый
# 4. кружка - красный
# 5. кружка - синий
# 6. кружка - зеленый
# 7. блокнот - красный
# 8. блокнот - синий
# 9. блокнот - зеленый

"""
Задача 4 (Сложная логика с тернарным оператором)
Вы обрабатываете данные о сотрудниках и хотите классифицировать их по уровню производительности
Дан список кортежей employees = [('Иван', 45), ('Мария', 92), ('Петр', 33), ('Анна', 67)],
где первый элемент - имя, второй - процент выполнения плана.

Создайте список performance, который содержит строки:
    "Отлично" для выполнения ≥ 90%
    "Хорошо" для выполнения ≥ 60%
    "Требует улучшения" для остальных
Используйте list comprehension с тернарным оператором.
"""

employees = [('Иван', 45), ('Мария', 92), ('Петр', 33), ('Анна', 67)]

performance = ["Отлично" if score >= 90 else
               "Хорошо" if score >= 60 else
               "Требует улучшения" for _, score in employees]

print("Оценка производительности сотрудников:")
for (name, score), x in zip(employees, performance):
    print(f"{name}: {score}% = {x}")
# Иван: 45% = Требует улучшения
# Мария: 92% = Отлично
# Петр: 33% = Требует улучшения
# Анна: 67% = Хорошо

"""
Задача 5 (Комплексная работа с данными)
Вы анализируете данные о продажах и хотите получить статистику по успешным менеджерам

Дан список словарей sales = [ {'name': 'Алексей', 'sales': 150, 'returns': 10},
{'name': 'Ольга', 'sales': 200, 'returns': 5},
{'name': 'Дмитрий', 'sales': 80, 'returns': 25},
{'name': 'Елена', 'sales': 300, 'returns': 8} ].
Создайте список top_managers, содержащий имена менеджеров,
у которых чистые продажи (sales - returns) ≥ 150
и процент возвратов (returns/sales × 100) < 10%.
"""

sales = [
    {'name': 'Алексей', 'sales': 150, 'returns': 10},
    {'name': 'Ольга', 'sales': 200, 'returns': 5},
    {'name': 'Дмитрий', 'sales': 80, 'returns': 25},
    {'name': 'Елена', 'sales': 300, 'returns': 8}
]

top_managers = [manager['name'] for manager in sales
                if (manager['sales'] - manager['returns'] >= 150)
                and (manager['returns'] / manager['sales'] * 100 < 10)]

print("Список топ-менеджеров:")
for manager in top_managers:
    print(manager) # Ольга, Елена