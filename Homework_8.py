"""
Задача 0
1. Создаем пустой список numbers
2. Начинаем while
3. Запрашиваем список чисел вида '1 2 10 -1'
4. split по пробелу
5. Фильтруем (list comp.) отрицательные и нецелые
6. Обновляем numbers
7. Цикл завершается, если пользователь ввел 0
8. В конце выводим numbers
"""

numbers = []
while True:
    user_input = input("Введите целые числа (0 для завершения): ")

    filtered_numbers = []
    for part in user_input.split():
        try:
            num = float(part)

            # Проверяем, не является ли число 0
            if num == 0:
                break  # Выходим из цикла for

            # Фильтруем неотрицательные и целые числа
            if num >= 0 and num.is_integer():
                filtered_numbers.append(int(num))
        except:
            continue  # Пропускаем нечисловые значения

    if "0" in user_input.split():
        numbers.extend(filtered_numbers)
        break

    numbers.extend(filtered_numbers)
    print(f"Добавлены числа: {filtered_numbers}, '\n' Всего: {len(numbers)}")

print(f"Полученный результат: {numbers}")

"""
Задача 1 (Базовое преобразование)
Дан список celsius = [0, 15, 25, 30, 40, 100].
Создайте новый список fahrenheit с помощью list comprehension,
где каждая температура преобразована по формуле: F = C × 9/5 + 32.

Дан список оценок grades = [45, 85, 92, 33, 67, 78, 90, 55, 29, 88].
Создайте новый список passed, содержащий только оценки выше или равные 60,
используя list comprehension с условием.
"""

celsius = [0, 15, 25, 30, 40, 100]
fahrenheit = [(c * 9/5) + 32 for c in celsius]
print(fahrenheit) # [32.0, 59.0, 77.0, 86.0, 104.0, 212.0]

# Вариант 1
grades = [45, 85, 92, 33, 67, 78, 90, 55, 29, 88]
passed = []
for grade in grades:
    if grade >= 60:
        passed.append(grade)

print(f"Оценки выше или равные 60 (вариант 1): {passed}") # [85, 92, 67, 78, 90, 88]

# Вариант 2
grades = [45, 85, 92, 33, 67, 78, 90, 55, 29, 88]
passed = [grade for grade in grades if grade >= 60]
print(f"Оценки выше или равные 60 (вариант 2): {passed}") # [85, 92, 67, 78, 90, 88]

"""
Задача 2 (Комбинированное преобразование и фильтрация)
Вы обрабатываете финансовые транзакции и хотите рассчитать налог только для доходных операций.

Дан список транзакций transactions = [100, -50, 200, -30, 150, -20, 300]
(положительные - доход, отрицательные - расход).
Создайте список taxes, содержащий 15% от каждой доходной транзакции
(только от положительных значений), используя list comprehension с условием
"""

transactions = [100, -50, 200, -30, 150, -20, 300]
taxes = [transaction * 0.15 for transaction in transactions if transaction > 0]
print(f"Налог 15%, удержанный от доходных транзакций: {taxes}") # [15.0, 30.0, 22.5, 45.0]

"""
Задача 3 (Работа со строками и вложенными циклами)
Вы генерируете все возможные комбинации товаров и цветов для каталога

Даны списки products = ['футболка', 'кружка', 'блокнот']
и colors = ['красный', 'синий', 'зеленый'].
Создайте список combinations, содержащий все возможные комбинации
в формате "товар - цвет", используя вложенные циклы в list comprehension.
"""

products = ['футболка', 'кружка', 'блокнот']
colors = ['красный', 'синий', 'зеленый']

combinations = [f"{product} - {color}" for product in products for color in colors]

print("Все комбинации товаров и цветов:")
for i, combination in enumerate(combinations, 1):
    print(f"{i}. {combination}")
# 1. футболка - красный
